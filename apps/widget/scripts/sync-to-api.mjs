import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "dist/widget.js");
const target = resolve(root, "../api/assets/widget.js");
const versionFile = resolve(root, "../api/assets/widget-version.txt");
const consoleVersionFile = resolve(root, "../console/src/generated/widget-version.ts");

mkdirSync(dirname(target), { recursive: true });
copyFileSync(source, target);

const version = createHash("sha256").update(readFileSync(source)).digest("hex").slice(0, 8);
writeFileSync(versionFile, `${version}\n`, "utf8");
mkdirSync(dirname(consoleVersionFile), { recursive: true });
writeFileSync(
  consoleVersionFile,
  `// Auto-generated by apps/widget/scripts/sync-to-api.mjs\nexport const WIDGET_ASSET_VERSION = "${version}";\n`,
  "utf8",
);

console.log(`==> synced widget.js -> ${target}`);
console.log(`==> widget version: ${version}`);
